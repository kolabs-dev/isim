#!/usr/bin/env python3
"""Writes isim/swift/overlays/AppIntents/Schemas.swift: the App Intents schema catalogs (AssistantSchemas, iOS 18, and
AppSchema, iOS 26: `.photos.openAsset`, `.mail.message`, ...) from Apple's API snapshot (isim/data/apple-api), so they
match Apple's names. Run it again after the documentation sweep refreshes the snapshot:

    python3 isim/tools/appintents-schemas.py
"""
import gzip
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SNAPSHOT = os.path.join(ROOT, "data/apple-api/apple-api.json.gz")
OUT = os.path.join(ROOT, "swift/overlays/AppIntents/Schemas.swift")
KINDS = ("Intent", "Entity", "Enum")


def symbols():
    seen = {}
    for path, decl, kind, *_ in json.load(gzip.open(SNAPSHOT))["symbols"]["AppIntents"]:
        p = path.replace("/documentation/appintents/", "")
        if p not in seen:
            seen[p] = (decl, kind)
    return seen


def catalog(syms, family):
    """{kind: {domain protocol: [members]}} and {kind: {static domain accessor: domain protocol}}"""
    members, accessors = {k: {} for k in KINDS}, {k: {} for k in KINDS}
    proto_rx = re.compile(r"^var (\w+): some (?:AssistantSchemas\.(Intent|Entity|Enum)|AppSchema(Intent|Entity|Enum))$")
    acc_rx = re.compile(r"^static var (\w+): some (?:AssistantSchemas|AppSchema)\.(\w+)$")
    for p, (decl, kind) in syms.items():
        parts = p.split("/")
        if family == "assistant" and parts[0] == "assistantschemas" and len(parts) == 3:
            m = proto_rx.match(decl)
            if m and kind == "property":
                container = syms.get("/".join(parts[:2]), ("",))[0].split(".")[-1]
                members[m.group(2)].setdefault(container, []).append(m.group(1))
            a = acc_rx.match(decl)
            if a and parts[1] in ("intent", "entity", "enum"):
                accessors[parts[1].capitalize()][a.group(1)] = a.group(2)
        if family == "app" and parts[0] == "appschema" and len(parts) == 3:
            m = proto_rx.match(decl)
            if m and kind == "property":
                container = syms.get("/".join(parts[:2]), ("",))[0].split(".")[-1]
                members[m.group(3)].setdefault(container, []).append(m.group(1))
        if family == "app" and parts[0] in ("appschemaintent", "appschemaentity", "appschemaenum") and len(parts) == 2:
            a = acc_rx.match(decl)
            if a:
                accessors[parts[0][len("appschema"):].capitalize()][a.group(1)] = a.group(2)
    return members, accessors


def swift(syms):
    out = ['// Generated by isim/tools/appintents-schemas.py from Apple\'s API snapshot: do not edit by hand.',
           '// The App Intents schema catalogs: AssistantSchemas (iOS 18, @AssistantIntent(schema:) …) and AppSchema (iOS 26,',
           '// @AppIntent(schema:) …). Each value carries its name ("photos.openAsset"); the macros record it on the type',
           '// (SchemaMacros.swift).',
           "import Foundation", ""]
    # AssistantSchemas
    members, accessors = catalog(syms, "assistant")
    out.append("@available(iOS 18.0, *)")
    out.append("public enum AssistantSchemas {")
    out.append("    public protocol Model: Sendable { var _isimSchemaName: String { get } }")
    for k in KINDS:
        out.append(f"    public protocol {k}: Model {{}}")
    for k in KINDS:
        domains = sorted(members[k])
        conf = ", ".join([k] + domains)
        out.append(f"    public struct {k}Schema: {conf} {{ public let _isimSchemaName: String; init(_ n: String) {{ _isimSchemaName = n }} }}")
    for k in KINDS:
        for d in sorted(members[k]):
            out.append(f"    public protocol {d}: Model {{}}")
    out.append("}")
    for k in KINDS:
        out.append("@available(iOS 18.0, *)")
        out.append(f"extension AssistantSchemas.{k} where Self == AssistantSchemas.{k}Schema {{")
        for name, proto in sorted(accessors[k].items()):
            out.append(f'    public static var {name}: some AssistantSchemas.{proto} {{ AssistantSchemas.{k}Schema("{name}") }}')
        out.append("}")
        for d in sorted(members[k]):
            out.append("@available(iOS 18.0, *)")
            out.append(f"extension AssistantSchemas.{d} {{")
            for m in sorted(set(members[k][d])):
                out.append(f'    public var {m}: some AssistantSchemas.{k} {{ AssistantSchemas.{k}Schema(_isimSchemaName + ".{m}") }}')
            out.append("}")
    # AppSchema
    members, accessors = catalog(syms, "app")
    out.append("")
    out.append("@available(iOS 26.0, *)")
    out.append("public struct AppSchema: Sendable {")
    for k in KINDS:
        for d in sorted(members[k]):
            out.append(f"    public protocol {d}: _IsimAppSchemaModel {{}}")
    out.append("}")
    out.append("public protocol _IsimAppSchemaModel: Sendable { var _isimSchemaName: String { get } }")
    for k in KINDS:
        out.append(f"@available(iOS 26.0, *) public protocol AppSchema{k}: _IsimAppSchemaModel {{}}")
    for k in KINDS:
        conf = ", ".join([f"AppSchema{k}"] + [f"AppSchema.{d}" for d in sorted(members[k])])
        out.append(f"@available(iOS 26.0, *) public struct _IsimAppSchema{k}: {conf} {{ public let _isimSchemaName: String; init(_ n: String) {{ _isimSchemaName = n }} }}")
        out.append("@available(iOS 26.0, *)")
        out.append(f"extension AppSchema{k} where Self == _IsimAppSchema{k} {{")
        for name, proto in sorted(accessors[k].items()):
            out.append(f'    public static var {name}: some AppSchema.{proto} {{ _IsimAppSchema{k}("{name}") }}')
        out.append("}")
        for d in sorted(members[k]):
            out.append("@available(iOS 26.0, *)")
            out.append(f"extension AppSchema.{d} {{")
            for m in sorted(set(members[k][d])):
                out.append(f'    public var {m}: some AppSchema{k} {{ _IsimAppSchema{k}(_isimSchemaName + ".{m}") }}')
            out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = swift(symbols())
    with open(OUT, "w") as f:
        f.write(text)
    print(f"{OUT}: {text.count(chr(10))} lines")
