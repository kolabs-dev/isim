#!/usr/bin/env python3
"""Writes isim/frameworks/Foundation/isim_unicode_norm.h: the canonical decompositions, the canonical compositions
and the combining classes of the Basic Multilingual Plane, from Python's unicodedata (Normalization.m uses them for
NFD / NFC). Hangul syllables are algorithmic and left out. Run it after a Python with a newer Unicode version."""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "frameworks" / "Foundation" / "isim_unicode_norm.h"


def main():
    decomp, comp, ccc = [], [], []
    for cp in range(0x10000):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        ch = chr(cp)
        d = unicodedata.decomposition(ch)
        if d and not d.startswith("<"):
            parts = [int(x, 16) for x in d.split()]
            if all(p <= 0xFFFF for p in parts):
                decomp.append((cp, parts[0], parts[1] if len(parts) > 1 else 0))
                if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch:
                    comp.append((parts[0], parts[1], cp))
        c = unicodedata.combining(ch)
        if c:
            ccc.append((cp, c))
    comp.sort()
    lines = [f"/* generated by isim/tools/gen-unicode-norm.py (Unicode {unicodedata.unidata_version}), BMP only; Hangul syllables are algorithmic */",
             "#pragma once", "#include <stdint.h>",
             "static const uint16_t isim_nfd_table[][3] = {   /* code point, first, second (0: a singleton) */"]
    lines += ["    {0x%04X, 0x%04X, 0x%04X}," % t for t in decomp]
    lines += ["};", "static const uint16_t isim_nfc_table[][3] = {   /* first, second -> composite (sorted) */"]
    lines += ["    {0x%04X, 0x%04X, 0x%04X}," % t for t in comp]
    lines += ["};", "static const uint16_t isim_ccc_table[][2] = {   /* code point, canonical combining class */"]
    lines += ["    {0x%04X, %d}," % t for t in ccc]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(decomp)} decompositions, {len(comp)} compositions, {len(ccc)} combining classes")


if __name__ == "__main__":
    sys.exit(main())
