#!/usr/bin/env python3
"""Generates isim's Accelerate new-LAPACK headers (issue #543): with ACCELERATE_NEW_LAPACK, Apple's SDK declares BLAS and
LAPACK with `__LAPACK_int`, const-correct pointers and `void` LAPACK results, each bound by an asm label to a
`<name>$NEWLAPACK` symbol. This reads the functions isim implements from its classic headers (cblas.h, clapack.h,
preprocessed), takes each one's parameter types and nullability from Apple's documented signatures
(data/apple-api/apple-api.json.gz), and writes sdk-src/Frameworks/Accelerate/lapack_new.h. The $NEWLAPACK symbols
are aliases of the classic functions (same LP64 ABI), listed in data/newlapack-symbols.txt for the link."""
import gzip
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
FW = os.path.join(ROOT, "sdk-src", "Frameworks")


def classic():
    """{name: (ret, [param types], [param names])} from the classic headers"""
    src = "#include <Accelerate/cblas.h>\n#include <Accelerate/clapack.h>\n"
    out = subprocess.run(["clang", "-E", "-P", "-x", "c", "-I", FW, "-"], input=src, text=True, capture_output=True, check=True).stdout
    out = re.sub(r"\s+", " ", out)
    decls = {}
    for m in re.finditer(r'extern __attribute__\(\(visibility\("default"\)\)\) ([\w ]+?) (\w+)\(([^;]*?)\);', out):
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
        params = [re.sub(r"\s*\b\w+$", "", a.strip()) if not a.strip().endswith("*") else a.strip() for a in args.split(",")]
        names = [(re.search(r"(\w+)$", a.strip()) or [None, ""])[1] if not a.strip().endswith("*") else "" for a in args.split(",")]
        decls[name] = (ret, params, names)
    return decls


def apple():
    """{name: [swift signature strings]} for Accelerate's C functions"""
    d = json.load(gzip.open(os.path.join(ROOT, "data", "apple-api", "apple-api.json.gz")))
    sigs = {}
    for e in d["symbols"]["Accelerate"]:
        m = re.match(r"func (\w+)\((.*)\)( -> (.+))?$", e[1])
        if m and e[2] == "func":
            sigs.setdefault(m.group(1), []).append((split(m.group(2)), m.group(4)))
    return sigs


def split(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<(": depth += 1
        if ch in ">)": depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out


SCALAR = {"Double": "double", "Float": "float", "CChar": "char", "__LAPACK_int": "__LAPACK_int", "Int32": "int",
          "CBLAS_ORDER": "const enum CBLAS_ORDER", "CBLAS_TRANSPOSE": "const enum CBLAS_TRANSPOSE", "CBLAS_UPLO": "const enum CBLAS_UPLO",
          "CBLAS_DIAG": "const enum CBLAS_DIAG", "CBLAS_SIDE": "const enum CBLAS_SIDE"}


def ctype(swift, old, cplx, const_hint):
    nullable = swift.endswith("?")
    sw = swift.rstrip("?")
    nn = " _Nullable" if nullable else " _Nonnull"
    m = re.match(r"(UnsafePointer|UnsafeMutablePointer)<(\w+)>$", sw)
    if m:
        base = SCALAR.get(m.group(2))
        if base is None: return None
        return ("const " if m.group(1) == "UnsafePointer" else "") + base + " *" + nn
    if sw == "OpaquePointer":
        const = old.startswith("const") or const_hint
        return ("const " if const else "") + cplx + " *" + nn
    if sw in SCALAR:
        return SCALAR[sw]
    return None


# integer arrays: their length from the function's (32-bit) scalars
ARRAYS = {("getrf", "ipiv"): "ISIM_MIN(v_m, v_n)", ("gbtrf", "ipiv"): "ISIM_MIN(v_m, v_n)", ("gesdd", "iwork"): "8 * ISIM_MIN(v_m, v_n)"}
ILP64_HEAD = """// isim Accelerate: the ILP64 new-LAPACK interface (ACCELERATE_NEW_LAPACK with ACCELERATE_LAPACK_ILP64), generated by
// tools/newlapack-headers.py. Each <name>$NEWLAPACK$ILP64 takes 64-bit integers, narrows them to the 32-bit
// implementation (a value that does not fit: LAPACK's info = -argument, BLAS's error report), copies integer arrays
// (ipiv, iwork) in and out with their lengths, and widens integer results. Adapted.
#include <Accelerate/Accelerate.h>
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#define ISIM_MIN(a, b) ((a) < (b) ? (a) : (b))
#define __LAPACK_float_complex _Complex float
#define __LAPACK_double_complex _Complex double
static int fits(long v) { return v >= INT_MIN && v <= INT_MAX; }
static void too_big(const char *fn, int arg) { fprintf(stderr, "isim: %s: argument %d does not fit 32 bits (isim's LAPACK is 32-bit inside)\\n", fn, arg); }
"""


def ilp64_wrapper(name, sym, ret, types, pnames):
    """C for <sym>$NEWLAPACK$ILP64 over the classic 32-bit function"""
    lapack = not name.startswith("cblas_")
    base = name[1:-1] if lapack else ""
    sig, pre, call, post, frees = [], [], [], [], []
    names = [n or f"p{i}" for i, n in enumerate(pnames)]
    has_info = lapack and "info" in names
    fail = ("{ if (info) *info = -%d; return; }" if has_info else "{ too_big(\"%s\", %d); return%s; }")
    for i, (t, n) in enumerate(zip(types, names)):
        t64 = t.replace("__LAPACK_int", "long").replace(" _Nonnull", "").replace(" _Nullable", "")
        sig.append(f"{t64} {n}")
        if t == "__LAPACK_int":                                       # BLAS scalar
            pre.append(f"if (!fits({n})) {{ too_big(\"{name}\", {i + 1}); return{' 0' if ret != 'void' else ''}; }}")
            call.append(f"(int){n}")
        elif "__LAPACK_int *" in t and ((base, n) in ARRAYS or n in ("ipiv", "iwork")):   # integer arrays
            length = ARRAYS.get((base, n), "v_n")
            pre.append(f"int len_{n} = {length} > 0 ? {length} : 0, *v_{n} = malloc(sizeof(int) * (size_t)(len_{n} ? len_{n} : 1));")
            pre.append(f"if (!v_{n}) {{ if (info) *info = -{i + 1}; return; }}")
            pre.append(f"for (int k = 0; k < len_{n}; k++) v_{n}[k] = {n} && fits({n}[k]) ? (int){n}[k] : 0;")
            call.append(f"v_{n}")
            if not t.startswith("const"): post.append(f"if ({n}) for (int k = 0; k < len_{n}; k++) {n}[k] = v_{n}[k];")
            frees.append(f"free(v_{n});")
        elif t.startswith("const __LAPACK_int *"):                    # LAPACK scalar in
            pre.append(f"int v_{n} = {n} ? (int){n}[0] : 0;")
            pre.append(f"if ({n} && !fits({n}[0])) " + (f"{{ if (info) *info = -{i + 1}; return; }}" if has_info else "return;"))
            call.append(f"{n} ? &v_{n} : NULL")
        elif t.startswith("__LAPACK_int *"):                          # info and other scalars out
            pre.append(f"int v_{n} = {n} && fits({n}[0]) ? (int){n}[0] : 0;")
            call.append(f"&v_{n}")
            post.append(f"if ({n}) {n}[0] = v_{n};")
        elif t.startswith("const __LAPACK_int"):
            call.append(n)
        elif "*" in t:
            call.append(f"(void *){n}")
        else:
            call.append(n)
    # array lengths may name scalars declared after them: declare the scalars first
    pre.sort(key=lambda l: 0 if l.startswith("int v_") and "len_" not in l else 1 if l.startswith("if (") and "fits" in l and "len_" not in l else 2)
    r64 = "long" if ret == "__LAPACK_int" else ret
    body = []
    body += pre
    if ret == "void":
        body.append(f"{name}({', '.join(call)});")
    else:
        body.append(f"{r64} r = ({r64}){name}({', '.join(call)});")
    body += post + frees
    if ret != "void": body.append("return r;")
    proto = f"{r64} isim64_{sym}({', '.join(sig)}) __asm(\"_{sym}$NEWLAPACK$ILP64\");"
    return proto + "\n" + f"{r64} isim64_{sym}({', '.join(sig)}) {{\n    " + "\n    ".join(body) + "\n}"


def main():
    old, sigs = classic(), apple()
    lines, symbols, skipped, wrappers = [], [], [], []
    for name in sorted(old):
        ret, params, pnames = old[name]
        cands = [s for s in sigs.get(name, []) if len(s[0]) == len(params)]
        if not cands:
            skipped.append(name); continue
        args, sret = cands[0]
        cplx = "__LAPACK_float_complex" if re.match(r"(cblas_)?(c|ic|sc|cs)", name) else "__LAPACK_double_complex"
        if name.startswith("cblas_"):
            core = name[len("cblas_"):]
            cplx = "__LAPACK_float_complex" if core[:1] == "c" or core[:2] in ("ic", "sc", "cs") else "__LAPACK_double_complex"
        else:
            cplx = "__LAPACK_float_complex" if name[0] == "c" else "__LAPACK_double_complex"
        # complex LAPACK: the real function's const-ness at the same position
        real = None
        if not name.startswith("cblas_") and name[0] in "cz":
            rn = {"c": "s", "z": "d"}[name[0]] + name[1:].replace("heev_", "syev_")
            real = next((s[0] for s in sigs.get(rn, []) if len(s[0]) == len(params)), None)
        out = []
        for i, (a, o) in enumerate(zip(args, params)):
            hint = bool(real) and real[i].startswith("UnsafePointer<")
            t = ctype(a, o, cplx, hint)
            if t is None: break
            out.append(t)
        if len(out) != len(params):
            skipped.append(name); continue
        if sret is None: r = "void"
        else: r = {"Double": "double", "Float": "float", "__LAPACK_int": "__LAPACK_int", "Int32": "int"}.get(sret)
        if r is None:
            skipped.append(name); continue
        sym = name[:-1] if name.endswith("_") else name
        lines.append(f"VECLIB_EXTERN {r} {name}({', '.join(out)}) __LAPACK_ALIAS({sym});")
        symbols.append((name, sym))
        wrappers.append(ilp64_wrapper(name, sym, r, out, pnames))
    header = """#pragma once
/* isim Accelerate: the new BLAS and LAPACK interface (ACCELERATE_NEW_LAPACK), generated by tools/newlapack-headers.py
   from isim's classic headers and Apple's documented signatures. Each function binds to `<name>$NEWLAPACK`, an alias
   of the classic one. With ACCELERATE_LAPACK_ILP64, `__LAPACK_int` is `long` and each function binds to
   `<name>$NEWLAPACK$ILP64`, a wrapper (frameworks/Accelerate/lapack_ilp64.c) over the 32-bit implementation. */
#include <Accelerate/vecLibTypes.h>
#if defined(ACCELERATE_LAPACK_ILP64)
typedef long __LAPACK_int;
#define __LAPACK_ALIAS(sym) __asm("_" #sym "$NEWLAPACK$ILP64")
#else
typedef int __LAPACK_int;
#define __LAPACK_ALIAS(sym) __asm("_" #sym "$NEWLAPACK")
#endif
#ifndef __LAPACK_float_complex
#define __LAPACK_float_complex _Complex float
#endif
#ifndef __LAPACK_double_complex
#define __LAPACK_double_complex _Complex double
#endif
"""
    with open(os.path.join(FW, "Accelerate", "lapack_new.h"), "w") as f:
        f.write(header + "\n".join(lines) + "\n#undef __LAPACK_ALIAS\n")
    with open(os.path.join(ROOT, "frameworks", "Accelerate", "lapack_ilp64.c"), "w") as f:
        f.write(ILP64_HEAD + "\n".join(wrappers) + "\n")
    with open(os.path.join(ROOT, "data", "newlapack-symbols.txt"), "w") as f:
        f.write("# classic symbol -> new-LAPACK alias (generated by tools/newlapack-headers.py)\n")
        for n, s in symbols: f.write(f"{n} {s}$NEWLAPACK\n")
    print(f"{len(lines)} functions; skipped {len(skipped)}: {' '.join(skipped)}", file=sys.stderr)


if __name__ == "__main__":
    main()
