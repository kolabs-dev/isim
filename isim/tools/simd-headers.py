#!/usr/bin/env python3
"""generates isim's C <simd/*.h> (issue #800): python3 tools/simd-headers.py [DIR] (default sdk-src/usr/include/simd)"""
import os, sys

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sdk-src", "usr", "include", "simd")
os.makedirs(OUT, exist_ok=True)
HDR = "/* isim simd for C and Objective-C (issue #800; generated by tools/simd-headers.py): Apple's <simd/%s> names over clang vector extensions,\n * header-only like Apple's. The functions are overloadable static inlines; Swift uses its own simd module, so they are\n * hidden from Swift (the types are not). */\n"

# name, C scalar, sizes, kind ('s' signed int, 'u' unsigned int, 'f' float), element bytes
SCALARS = [
    ("char", "char", [2, 3, 4, 8, 16, 32, 64], "s", 1), ("uchar", "unsigned char", [2, 3, 4, 8, 16, 32, 64], "u", 1),
    ("short", "short", [2, 3, 4, 8, 16, 32], "s", 2), ("ushort", "unsigned short", [2, 3, 4, 8, 16, 32], "u", 2),
    ("int", "int", [2, 3, 4, 8, 16], "s", 4), ("uint", "unsigned int", [2, 3, 4, 8, 16], "u", 4),
    ("long", "long", [2, 3, 4, 8], "s", 8), ("ulong", "unsigned long", [2, 3, 4, 8], "u", 8),
    ("half", "_Float16", [2, 3, 4, 8, 16, 32], "f", 2), ("float", "float", [2, 3, 4, 8, 16], "f", 4),
    ("double", "double", [2, 3, 4, 8], "f", 8),
]
FLOATS = [s for s in SCALARS if s[3] == "f"]
MASK = {1: "char", 2: "short", 4: "int", 8: "long"}
F = "static inline __attribute__((__overloadable__, __always_inline__, __nodebug__))"

def w(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(text)

# ---- base.h
w("base.h", "#pragma once\n" + HDR % "base.h" + """#define SIMD_COMPILER_HAS_REQUIRED_FEATURES 1
#define SIMD_OVERLOAD __attribute__((__overloadable__))
#define SIMD_CFUNC static inline __attribute__((__overloadable__, __always_inline__, __nodebug__))
#define SIMD_NOINLINE static __attribute__((__overloadable__, __noinline__))
#define SIMD_CONST __attribute__((__const__))
#if defined(__swift__)
#define __ISIM_SIMD_FUNCTIONS 0
#else
#define __ISIM_SIMD_FUNCTIONS 1
#endif
""")

# ---- vector_types.h, packed.h
t = ["#pragma once", HDR % "vector_types.h", '#include <simd/base.h>', '#include <stdint.h>', ""]
p = ["#pragma once", HDR % "packed.h", '#include <simd/vector_types.h>', ""]
for name, c, sizes, kind, size in SCALARS:
    t.append(f"typedef {c} simd_{name}1;")
    t.append(f"typedef {c} vector_{name}1;" if name != "half" else "typedef _Float16 vector_half1;")
    for n in sizes:
        t.append(f"typedef __attribute__((__ext_vector_type__({n}))) {c} simd_{name}{n};")
        t.append(f"typedef simd_{name}{n} vector_{name}{n};")
        if n != 3:
            p.append(f"typedef __attribute__((__ext_vector_type__({n}), __aligned__({size}))) {c} simd_packed_{name}{n};")
            p.append(f"typedef simd_packed_{name}{n} packed_{name}{n};")
            p.append(f"typedef simd_packed_{name}{n} vector_packed_{name}{n};")
    t.append("")
t.append("#include <simd/packed.h>")
w("vector_types.h", "\n".join(t) + "\n")
w("packed.h", "\n".join(p) + "\n")

# ---- matrix_types.h
m = ["#pragma once", HDR % "matrix_types.h", '#include <simd/vector_types.h>', ""]
for name, c, sizes, kind, size in FLOATS:
    for cols in (2, 3, 4):
        for rows in (2, 3, 4):
            m.append(f"typedef struct {{ simd_{name}{rows} columns[{cols}]; }} simd_{name}{cols}x{rows};")
            m.append(f"typedef simd_{name}{cols}x{rows} matrix_{name}{cols}x{rows};")
    if name != "half":
        m.append(f"typedef struct {{ simd_{name}4 vector; }} simd_quat{name[0]};")
    m.append("")
w("matrix_types.h", "\n".join(m) + "\n")

# ---- functions on vectors
c = ["#pragma once", HDR % "common.h, geometry.h, logic.h, math.h and conversion.h", '#include <simd/vector_types.h>', '#include <math.h>',
     "#if __ISIM_SIMD_FUNCTIONS", ""]
def vt(name, n): return f"simd_{name}{n}" if n > 1 else f"simd_{name}1"
for name, cs, sizes, kind, size in SCALARS:
    for n in [1] + sizes:
        T = vt(name, n)
        sc = f"simd_{name}1"
        vec = n > 1
        lanes = f"for (int i = 0; i < {n}; i++)"
        # min / max / clamp
        if vec:
            c.append(f"{F} {T} simd_min({T} x, {T} y) {{ return __builtin_elementwise_min(x, y); }}")
            c.append(f"{F} {T} simd_max({T} x, {T} y) {{ return __builtin_elementwise_max(x, y); }}")
        else:
            c.append(f"{F} {T} simd_min({T} x, {T} y) {{ return x < y ? x : y; }}")
            c.append(f"{F} {T} simd_max({T} x, {T} y) {{ return x > y ? x : y; }}")
        c.append(f"{F} {T} simd_clamp({T} x, {T} lo, {T} hi) {{ return simd_min(simd_max(x, lo), hi); }}")
        if kind != "u":
            c.append(f"{F} {T} simd_abs({T} x) {{ return " + ("__builtin_elementwise_abs(x)" if vec else ("x < 0 ? -x : x" if kind == "s" else "__builtin_fabs(x)" if name == "double" else "(" + T + ")__builtin_fabsf((float)x)")) + "; }")
        if vec:
            if kind == "f":
                c.append(f"{F} {sc} simd_reduce_add({T} x) {{ {sc} r = 0; {lanes} r += x[i]; return r; }}")
                c.append(f"{F} {sc} simd_reduce_min({T} x) {{ {sc} r = x[0]; for (int i = 1; i < {n}; i++) r = x[i] < r ? x[i] : r; return r; }}")
                c.append(f"{F} {sc} simd_reduce_max({T} x) {{ {sc} r = x[0]; for (int i = 1; i < {n}; i++) r = x[i] > r ? x[i] : r; return r; }}")
            else:
                c.append(f"{F} {sc} simd_reduce_add({T} x) {{ return __builtin_reduce_add(x); }}")
                c.append(f"{F} {sc} simd_reduce_min({T} x) {{ return __builtin_reduce_min(x); }}")
                c.append(f"{F} {sc} simd_reduce_max({T} x) {{ return __builtin_reduce_max(x); }}")
        if kind == "f":
            one = f"({T})1"
            c.append(f"{F} {T} simd_sign({T} x) {{ return " + ("__builtin_elementwise_copysign(" + one + ", x) * (" + T + ")(x != 0 ? -1 : 0) * -1" if False else
                     (f"({T})((x > 0) ? 1 : ((x < 0) ? -1 : 0))" if not vec else f"__builtin_convertvector((x > 0), {T}) * -1 - __builtin_convertvector((x < 0), {T}) * -1")) + "; }")
            c.append(f"{F} {T} simd_mix({T} x, {T} y, {T} t) {{ return x + t * (y - x); }}")
            c.append(f"{F} {T} simd_recip({T} x) {{ return 1 / x; }}")
            c.append(f"{F} {T} simd_fast_recip({T} x) {{ return 1 / x; }}")
            c.append(f"{F} {T} simd_precise_recip({T} x) {{ return 1 / x; }}")
            sq = "__builtin_elementwise_sqrt(x)" if vec else ("__builtin_sqrt(x)" if name == "double" else f"({T})__builtin_sqrtf((float)x)")
            c.append(f"{F} {T} simd_rsqrt({T} x) {{ return 1 / {sq}; }}")
            c.append(f"{F} {T} simd_fast_rsqrt({T} x) {{ return 1 / {sq}; }}")
            c.append(f"{F} {T} simd_precise_rsqrt({T} x) {{ return 1 / {sq}; }}")
            fl = "__builtin_elementwise_floor(x)" if vec else ("__builtin_floor(x)" if name == "double" else f"({T})__builtin_floorf((float)x)")
            c.append(f"{F} {T} simd_fract({T} x) {{ return simd_min(x - {fl}, ({T})0x1.fffffep-1f); }}")
            if vec:
                c.append(f"{F} {T} simd_step({T} edge, {T} x) {{ return __builtin_convertvector(!(x < edge), {T}) * -1; }}")
            else:
                c.append(f"{F} {T} simd_step({T} edge, {T} x) {{ return x < edge ? 0 : 1; }}")
            c.append(f"{F} {T} simd_smoothstep({T} e0, {T} e1, {T} x) {{ {T} t = simd_clamp((x - e0) / (e1 - e0), ({T})0, ({T})1); return t * t * (3 - 2 * t); }}")
            c.append(f"{F} {T} simd_muladd({T} x, {T} y, {T} z) {{ return x * y + z; }}")
            if vec:
                # geometry
                c.append(f"{F} {sc} simd_dot({T} x, {T} y) {{ return simd_reduce_add(x * y); }}")
                c.append(f"{F} {sc} simd_length_squared({T} x) {{ return simd_dot(x, x); }}")
                c.append(f"{F} {sc} simd_length({T} x) {{ return " + ("__builtin_sqrt(simd_length_squared(x))" if name == "double" else f"({sc})__builtin_sqrtf((float)simd_length_squared(x))") + "; }")
                c.append(f"{F} {sc} simd_precise_length({T} x) {{ return simd_length(x); }}")
                c.append(f"{F} {sc} simd_fast_length({T} x) {{ return simd_length(x); }}")
                c.append(f"{F} {sc} simd_norm_one({T} x) {{ return simd_reduce_add(__builtin_elementwise_abs(x)); }}")
                c.append(f"{F} {sc} simd_norm_inf({T} x) {{ return simd_reduce_max(__builtin_elementwise_abs(x)); }}")
                c.append(f"{F} {sc} simd_distance_squared({T} x, {T} y) {{ return simd_length_squared(x - y); }}")
                c.append(f"{F} {sc} simd_distance({T} x, {T} y) {{ return simd_length(x - y); }}")
                c.append(f"{F} {sc} simd_precise_distance({T} x, {T} y) {{ return simd_distance(x, y); }}")
                c.append(f"{F} {sc} simd_fast_distance({T} x, {T} y) {{ return simd_distance(x, y); }}")
                c.append(f"{F} {T} simd_normalize({T} x) {{ return x / simd_length(x); }}")
                c.append(f"{F} {T} simd_precise_normalize({T} x) {{ return simd_normalize(x); }}")
                c.append(f"{F} {T} simd_fast_normalize({T} x) {{ return simd_normalize(x); }}")
                c.append(f"{F} {T} simd_project({T} x, {T} y) {{ return simd_dot(x, y) / simd_dot(y, y) * y; }}")
                c.append(f"{F} {T} simd_precise_project({T} x, {T} y) {{ return simd_project(x, y); }}")
                c.append(f"{F} {T} simd_fast_project({T} x, {T} y) {{ return simd_project(x, y); }}")
                c.append(f"{F} {T} simd_reflect({T} x, {T} n) {{ return x - 2 * simd_dot(x, n) * n; }}")
                c.append(f"{F} {T} simd_refract({T} x, {T} n, {sc} eta) {{ {sc} k = 1 - eta * eta * (1 - simd_dot(x, n) * simd_dot(x, n)); "
                         f"return k < 0 ? ({T})0 : eta * x - (eta * simd_dot(x, n) + " + ("__builtin_sqrt(k)" if name == "double" else f"({sc})__builtin_sqrtf((float)k)") + ") * n; }")
                if n == 2:
                    three = vt(name, 3)
                    c.append(f"{F} {three} simd_cross({T} x, {T} y) {{ return ({three}){{ 0, 0, x.x * y.y - x.y * y.x }}; }}")
                if n == 3:
                    c.append(f"{F} {T} simd_cross({T} x, {T} y) {{ return ({T}){{ x.y * y.z - x.z * y.y, x.z * y.x - x.x * y.z, x.x * y.y - x.y * y.x }}; }}")
                # element-wise math (math.h's __tg_ forms, used by <tgmath.h>)
                for fn in ("sqrt", "floor", "ceil", "trunc", "sin", "cos", "exp", "exp2", "log", "log2", "log10", "round", "rint", "fabs"):
                    b = {"fabs": "abs", "round": "round", "rint": "rint"}.get(fn, fn)
                    c.append(f"{F} {T} __tg_{fn}({T} x) {{ return __builtin_elementwise_{b}(x); }}")
                    if fn in ("sqrt", "floor", "ceil", "trunc", "sin", "cos", "exp", "log", "round", "fabs"):
                        pass
                for fn in ("tan", "asin", "acos", "atan", "cbrt", "sinh", "cosh", "tanh", "expm1", "log1p"):
                    cf = fn if name == "double" else fn + "f"
                    c.append(f"{F} {T} __tg_{fn}({T} x) {{ {T} r; {lanes} r[i] = ({sc}){cf}(({ 'double' if name == 'double' else 'float'})x[i]); return r; }}")
                for fn in ("atan2", "pow", "fmod", "hypot", "copysign", "fdim", "nextafter", "remainder"):
                    cf = fn if name == "double" else fn + "f"
                    c.append(f"{F} {T} __tg_{fn}({T} x, {T} y) {{ {T} r; {lanes} r[i] = ({sc}){cf}(({ 'double' if name == 'double' else 'float'})x[i], ({ 'double' if name == 'double' else 'float'})y[i]); return r; }}")
                c.append(f"{F} {T} __tg_fmin({T} x, {T} y) {{ return __builtin_elementwise_min(x, y); }}")
                c.append(f"{F} {T} __tg_fmax({T} x, {T} y) {{ return __builtin_elementwise_max(x, y); }}")
                c.append(f"{F} {T} __tg_fma({T} x, {T} y, {T} z) {{ return __builtin_elementwise_fma(x, y, z); }}")
        if vec:
            mk = MASK[size]
            M = f"simd_{mk}{n}"
            # logic
            c.append(f"{F} {T} simd_bitselect({T} x, {T} y, {M} mask) {{ {M} a, b; __builtin_memcpy(&a, &x, sizeof a); __builtin_memcpy(&b, &y, sizeof b); "
                     f"a = (a & ~mask) | (b & mask); {T} r; __builtin_memcpy(&r, &a, sizeof r); return r; }}")
            c.append(f"{F} {T} simd_select({T} x, {T} y, {M} mask) {{ return simd_bitselect(x, y, mask >> {size * 8 - 1}); }}")
        c.append("")
# logic on masks
for name, cs, sizes, kind, size in SCALARS:
    if kind == "f":
        continue
    for n in sizes:
        T = vt(name, n)
        if kind == "s":
            c.append(f"{F} _Bool simd_any({T} x) {{ return __builtin_reduce_or(x < 0); }}")
            c.append(f"{F} _Bool simd_all({T} x) {{ return __builtin_reduce_and(x < 0); }}")
        else:
            c.append(f"{F} _Bool simd_any({T} x) {{ return __builtin_reduce_or(x >> {size * 8 - 1}) != 0; }}")
            c.append(f"{F} _Bool simd_all({T} x) {{ return __builtin_reduce_and(x >> {size * 8 - 1}) != 0; }}")
# conversions and vector_make
for name, cs, sizes, kind, size in SCALARS:
    for n in sizes:
        T = vt(name, n)
        for oname, ocs, osizes, okind, osize in SCALARS:
            if n in osizes:
                c.append(f"{F} {T} simd_{name}({vt(oname, n)} x) {{ return __builtin_convertvector(x, {T}); }}")
c.append("")
for name, cs, sizes, kind, size in SCALARS:
    s = f"simd_{name}1"
    for n in sizes:
        T = vt(name, n)
        if n <= 4:
            args = ", ".join(f"{s} {v}" for v in "xyzw"[:n])
            c.append(f"{F} {T} simd_make_{name}{n}({args}) {{ return ({T}){{ {', '.join('xyzw'[:n])} }}; }}")
            if n == 3:
                c.append(f"{F} {T} simd_make_{name}3({s} x, {vt(name, 2)} yz) {{ return ({T}){{ x, yz.x, yz.y }}; }}")
                c.append(f"{F} {T} simd_make_{name}3({vt(name, 2)} xy, {s} z) {{ return ({T}){{ xy.x, xy.y, z }}; }}")
            if n == 4:
                c.append(f"{F} {T} simd_make_{name}4({vt(name, 3)} xyz, {s} w) {{ return ({T}){{ xyz.x, xyz.y, xyz.z, w }}; }}")
                c.append(f"{F} {T} simd_make_{name}4({s} x, {vt(name, 3)} yzw) {{ return ({T}){{ x, yzw.x, yzw.y, yzw.z }}; }}")
                c.append(f"{F} {T} simd_make_{name}4({vt(name, 2)} xy, {vt(name, 2)} zw) {{ return ({T}){{ xy.x, xy.y, zw.x, zw.y }}; }}")
        c.append(f"{F} {T} simd_make_{name}{n}({s} x) {{ {T} r = 0; r[0] = x; return r; }}")
        c.append(f"{F} {T} simd_make_{name}{n}_undef({s} x) {{ {T} r = 0; r[0] = x; return r; }}")
        for m in sizes:
            if m == n:
                c.append(f"{F} {T} simd_make_{name}{n}({T} x) {{ return x; }}")
                continue
            M = vt(name, m)
            k = min(n, m)
            c.append(f"{F} {T} simd_make_{name}{n}({M} x) {{ {T} r = 0; for (int i = 0; i < {k}; i++) r[i] = x[i]; return r; }}")
            if m < n:
                c.append(f"{F} {T} simd_make_{name}{n}_undef({M} x) {{ return simd_make_{name}{n}(x); }}")
c.append("")
c.append("#endif")
w("vector.h", "\n".join(c) + "\n")
for h in ("common.h", "geometry.h", "logic.h", "math.h", "conversion.h", "vector_make.h"):
    w(h, f"#pragma once\n/* isim simd: <simd/{h}> is part of <simd/vector.h> (issue #800) */\n#include <simd/vector.h>\n")

# ---- matrix.h and quaternion.h
mx = ["#pragma once", HDR % "matrix.h", '#include <simd/matrix_types.h>', '#include <simd/vector.h>', "#if __ISIM_SIMD_FUNCTIONS", ""]
for name, cs, sizes, kind, size in FLOATS:
    s = f"simd_{name}1"
    for cols in (2, 3, 4):
        for rows in (2, 3, 4):
            M = f"simd_{name}{cols}x{rows}"
            V = vt(name, rows)  # a column
            R = vt(name, cols)  # a row
            cargs = ", ".join(f"{V} c{i}" for i in range(cols))
            mx.append(f"{F} {M} simd_matrix({cargs}) {{ {M} m = {{ {{ {', '.join(f'c{i}' for i in range(cols))} }} }}; return m; }}")
            rargs = ", ".join(f"{R} r{i}" for i in range(rows))
            mx.append(f"{F} {M} simd_matrix_from_rows({rargs}) {{ {R} r[{rows}] = {{ {', '.join(f'r{i}' for i in range(rows))} }}; {M} m; "
                      f"for (int c = 0; c < {cols}; c++) for (int i = 0; i < {rows}; i++) m.columns[c][i] = r[i][c]; return m; }}")
            mx.append(f"{F} {M} simd_add({M} a, {M} b) {{ for (int c = 0; c < {cols}; c++) a.columns[c] += b.columns[c]; return a; }}")
            mx.append(f"{F} {M} simd_sub({M} a, {M} b) {{ for (int c = 0; c < {cols}; c++) a.columns[c] -= b.columns[c]; return a; }}")
            mx.append(f"{F} {M} simd_linear_combination({s} a, {M} x, {s} b, {M} y) {{ for (int c = 0; c < {cols}; c++) x.columns[c] = a * x.columns[c] + b * y.columns[c]; return x; }}")
            mx.append(f"{F} {M} simd_mul({s} a, {M} x) {{ for (int c = 0; c < {cols}; c++) x.columns[c] *= a; return x; }}")
            mx.append(f"{F} {V} simd_mul({M} m, {R} v) {{ {V} r = 0; for (int c = 0; c < {cols}; c++) r += m.columns[c] * v[c]; return r; }}")
            mx.append(f"{F} {R} simd_mul({V} v, {M} m) {{ {R} r; for (int c = 0; c < {cols}; c++) r[c] = simd_dot(v, m.columns[c]); return r; }}")
            T = f"simd_{name}{rows}x{cols}"
            mx.append(f"{F} {T} simd_transpose({M} m) {{ {T} t; for (int c = 0; c < {cols}; c++) for (int r = 0; r < {rows}; r++) t.columns[r][c] = m.columns[c][r]; return t; }}")
            mx.append(f"{F} _Bool simd_equal({M} a, {M} b) {{ for (int c = 0; c < {cols}; c++) for (int r = 0; r < {rows}; r++) if (a.columns[c][r] != b.columns[c][r]) return 0; return 1; }}")
            mx.append(f"{F} _Bool simd_almost_equal_elements({M} a, {M} b, {s} tol) {{ for (int c = 0; c < {cols}; c++) for (int r = 0; r < {rows}; r++) "
                      f"if (simd_abs(a.columns[c][r] - b.columns[c][r]) > tol) return 0; return 1; }}")
            mx.append(f"{F} _Bool simd_almost_equal_elements_relative({M} a, {M} b, {s} tol) {{ for (int c = 0; c < {cols}; c++) for (int r = 0; r < {rows}; r++) "
                      f"if (simd_abs(a.columns[c][r] - b.columns[c][r]) > tol * simd_abs(a.columns[c][r])) return 0; return 1; }}")
    # products of matrices
    for k in (2, 3, 4):        # a: k columns x rows; b: cols columns x k rows
        for rows in (2, 3, 4):
            for cols in (2, 3, 4):
                A, B, Cm = f"simd_{name}{k}x{rows}", f"simd_{name}{cols}x{k}", f"simd_{name}{cols}x{rows}"
                mx.append(f"{F} {Cm} simd_mul({A} a, {B} b) {{ {Cm} r; for (int c = 0; c < {cols}; c++) r.columns[c] = simd_mul(a, b.columns[c]); return r; }}")
    for n in (2, 3, 4):
        M = f"simd_{name}{n}x{n}"
        V = vt(name, n)
        mx.append(f"{F} {M} simd_diagonal_matrix({V} d) {{ {M} m; for (int c = 0; c < {n}; c++) {{ m.columns[c] = 0; m.columns[c][c] = d[c]; }} return m; }}")
        if name != "half":
            mx.append(f"static const {M} matrix_identity_{name}{n}x{n} = {{ {{ " + ", ".join("{" + ", ".join("1" if i == j else "0" for i in range(n)) + "}" for j in range(n)) + " } };")
        mx.append(f"{F} {s} simd_trace({M} m) {{ {s} t = 0; for (int i = 0; i < {n}; i++) t += m.columns[i][i]; return t; }}")
    # determinants and inverses
